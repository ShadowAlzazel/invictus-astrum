#!/usr/bin/env python3
"""Generate a complete FORWARD or RESERVE Classis fleet TOML.

Examples:
    python tools/fleet_maker.py forward --id alcyone-classis-2 --name "Alcyone Classis II"
    python tools/fleet_maker.py reserve --id luna-classis-1 --name "Luna Classis I" --profile high

The output contains fleet units only. Scenario placement belongs in the scenario's
[[contact]] entries, as described in data/fleets/README.md.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def quote(value: str) -> str:
    """Quote a TOML basic string."""
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


class Fleet:
    def __init__(self, fleet_id: str, name: str, faction: str, profile: str):
        self.fleet_id, self.name, self.faction, self.profile = fleet_id, name, faction, profile
        self.units: list[dict[str, str]] = []

    def unit(self, uid: str, callsign: str, echelon: str, parent: str | None = None,
             ship_class: str | None = None, flag: bool = False) -> None:
        row = {"id": uid, "callsign": callsign, "echelon": echelon}
        if parent:
            row["formation"] = parent
        if ship_class:
            row["class"] = ship_class
        if flag:
            row["flag"] = "true"
        self.units.append(row)

    def ship_count(self, low: int, high: int) -> int:
        return low if self.profile == "low" else high

    def squadron(self, sid: str, name: str, parent: str, cls: str, count: tuple[int, int]) -> None:
        self.unit(sid, name, "squadron", parent)
        for n in range(1, self.ship_count(*count) + 1):
            self.unit(f"{sid}-{n}", f"{name} {n}", "ship", sid, cls)

    def flotilla(self, fid: str, name: str, parent: str, squadrons: list[tuple[str, str, str, tuple[int, int]]]) -> None:
        self.unit(fid, name, "flotilla", parent)
        for suffix, sname, cls, count in squadrons:
            self.squadron(f"{fid}-{suffix}", sname, fid, cls, count)

    def render(self) -> str:
        lines = ["# Generated by tools/fleet_maker.py. Edit callsigns and hull names as desired.",
                 "# Fleet structure is separate from scenario placement.", "", "[fleet]",
                 f"id = {quote(self.fleet_id)}", f"name = {quote(self.name)}",
                 f"faction = {quote(self.faction)}", f"notes = {quote(self.profile.upper() + ' count profile; generated ' + self.kind + ' Classis.')}",
                 "", "[[unit]]", f"id = {quote(self.fleet_id)}", f"callsign = {quote(self.name)}",
                 'affiliation = "friend"', f"faction = {quote(self.faction)}", 'echelon = "classis"',
                 f"flag = {quote(self.flagship)}", ""]
        for u in self.units:
            lines += ["[[unit]]"]
            for key in ("id", "callsign"):
                lines.append(f"{key} = {quote(u[key])}")
            lines.append('affiliation = "friend"')
            lines.append(f"echelon = {quote(u['echelon'])}")
            if "formation" in u:
                lines.append(f"formation = {quote(u['formation'])}")
            if "class" in u:
                lines.append(f"class = {quote(u['class'])}")
            lines.append("")
        return "\n".join(lines)

    @property
    def kind(self) -> str:
        return self._kind


def add_forward(f: Fleet) -> None:
    f._kind = "FORWARD"
    f.flagship = "tf1-lf1-bs-1"
    # Three complete task forces. Each contains three line flotillas, plus task-force
    # level line/picket, vanguard, and escort squadrons.
    for t in range(1, 4):
        tf = f"tf{t}"
        f.unit(tf, f"Task Force {t}", "task-force", f.fleet_id)
        for l in range(1, 4):
            fid = f"{tf}-lf{l}"
            f.flotilla(fid, f"Line Flotilla {l}", tf, [
                ("bs", f"Battle Squadron {l}", "papilion", (4, 5)),
                ("ls", f"Line Squadron {l}", "phalaena", (3, 4)),
                ("p1", f"Picket Squadron {l}A", "phalaena", (2, 3)),
                ("p2", f"Picket Squadron {l}B", "phalaena", (2, 3)),
            ])
        for n in range(1, 3):
            f.squadron(f"{tf}-lp{n}", f"Line Picket Squadron {n}", tf, "phalaena", (3, 4))
        f.squadron(f"{tf}-vs", "Vanguard Squadron", tf, "papilion", (3, 4))
        f.squadron(f"{tf}-es", "Escort Squadron", tf, "aeshna", (2, 3))

    f.flotilla("battle-flotilla", "Battle Flotilla", f.fleet_id, [
        ("bs1", "Battle Squadron 1", "papilion", (4, 5)),
        ("bs2", "Battle Squadron 2", "papilion", (4, 5)),
        ("ls1", "Line Squadron 1", "phalaena", (3, 4)),
        ("ls2", "Line Squadron 2", "phalaena", (3, 4)),
    ])
    f.flotilla("escort-flotilla", "Escort Flotilla", f.fleet_id, [
        ("es1", "Escort Squadron 1", "aeshna", (2, 3)),
        ("es2", "Escort Squadron 2", "aeshna", (2, 3)),
        ("les1", "Light Escort Squadron 1", "phalaena", (3, 5)),
        ("les2", "Light Escort Squadron 2", "phalaena", (3, 5)),
    ])
    for n in range(1, 4):
        f.squadron(f"line-picket-{n}", f"Line Picket Squadron {n}", f.fleet_id, "phalaena", (3, 4))
    f.squadron("strike-squadron", "Strike Squadron", f.fleet_id, "papilion", (5, 5))
    add_auxiliaries(f, "aux", f.fleet_id, tender=(12, 16), repair=(2, 2), watch=(5, 6), guard=(8, 12))


def add_auxiliaries(f: Fleet, prefix: str, parent: str, tender: tuple[int, int], repair: tuple[int, int],
                    watch: tuple[int, int], guard: tuple[int, int]) -> None:
    f.unit(prefix, "Auxiliary Group", "flotilla", parent)
    for slug, label, cls, counts in [
        ("tender", "Coccinella Mollitrix Tender", "coccinella", tender),
        ("repair", "Tarantulae Nutrix Repair Ship", "tarantulae", repair),
        ("watch", "Salticidae Vigil Watch and Relay", "salticidae", watch),
        ("guard", "Bacillus Lictrix Headquarters and Transport Guard", "bacillus", guard),
    ]:
        sid = f"{prefix}-{slug}"
        f.unit(sid, f"{label} Squadron", "squadron", prefix)
        for n in range(1, f.ship_count(*counts) + 1):
            f.unit(f"{sid}-{n}", f"{label} {n}", "ship", sid, cls)


def add_reserve(f: Fleet) -> None:
    f._kind = "RESERVE"
    f.flagship = "old-forest-tf-old-line-bs1-1"
    # Task forces are organizational garden formations; normally one is lent forward.
    for n in range(1, 4):
        f.unit(f"task-force-{n}", f"Reserve Task Force {n} (Garden)", "task-force", f.fleet_id)
    for flot in range(1, 3):
        fid = f"picket-flotilla-{flot}"
        f.unit(fid, f"Picket Flotilla {flot} (Garden)", "flotilla", f.fleet_id)
        for s in range(1, 3):
            f.squadron(f"{fid}-line-{s}", f"Line Squadron {s}", fid, "phalaena", (4, 5))
        for s in range(1, 4):
            f.squadron(f"{fid}-picket-{s}", f"Picket Squadron {s}", fid, "phalaena", (2, 3))
    f.flotilla("escort-flotilla", "Escort Flotilla (Garden)", f.fleet_id, [
        ("es1", "Escort Squadron 1", "aeshna", (2, 3)),
        ("es2", "Escort Squadron 2", "aeshna", (2, 3)),
        ("les1", "Light Escort Squadron 1", "phalaena", (3, 5)),
        ("les2", "Light Escort Squadron 2", "phalaena", (3, 5)),
    ])
    for n in range(1, 4):
        f.squadron(f"line-picket-{n}", f"Line Picket Squadron {n}", f.fleet_id, "phalaena", (3, 4))

    old = "old-forest-tf"
    f.unit(old, "Old Forest Task Force", "task-force", f.fleet_id)
    f.flotilla("old-forest-tf-old-line", "Old Line Flotilla", old, [
        ("bs1", "Battle Squadron 1", "yggdrasil", (4, 5)),
        ("bs2", "Battle Squadron 2", "yggdrasil", (4, 5)),
        ("em1", "Emitter Squadron 1", "holzweiber", (4, 5)),
        ("em2", "Emitter Squadron 2", "holzweiber", (4, 5)),
    ])
    f.flotilla("old-forest-tf-screen", "Screen Flotilla", old, [
        ("screen1", "Screen Squadron 1", "holzweiber", (4, 5)),
        ("screen2", "Screen Squadron 2", "holzweiber", (4, 5)),
        ("screen3", "Screen Squadron 3", "holzweiber", (4, 5)),
        ("picket1", "Picket Squadron 1", "dryad", (2, 3)),
        ("picket2", "Picket Squadron 2", "dryad", (2, 3)),
    ])
    f.flotilla("old-forest-tf-dryad-picket", "Dryad Picket Flotilla", old, [
        (f"picket{s}", f"Picket Squadron {s}", "dryad", (2, 3)) for s in range(1, 6)
    ])
    add_auxiliaries(f, "aux", f.fleet_id, tender=(12, 16), repair=(2, 2), watch=(5, 6), guard=(8, 12))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("type", choices=("forward", "reserve"), help="Classis structure to generate")
    parser.add_argument("--id", required=True, dest="fleet_id", help="Fleet ID and default output filename")
    parser.add_argument("--name", required=True, help="Fleet callsign/name")
    parser.add_argument("--faction", default="avc", help="Faction ID (default: avc)")
    parser.add_argument("--profile", choices=("low", "high"), default="low",
                        help="Choose low or high end of each stated range (default: low)")
    parser.add_argument("--output", type=Path, help="Output path (default: data/fleets/<id>.toml)")
    parser.add_argument("--force", action="store_true", help="Replace an existing output file")
    args = parser.parse_args()
    if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_-]*", args.fleet_id):
        parser.error("--id may contain only letters, numbers, hyphens, and underscores")
    output = args.output or Path(__file__).resolve().parent.parent / "data" / "fleets" / f"{args.fleet_id}.toml"
    if output.exists() and not args.force:
        parser.error(f"{output} already exists; choose another --id/path or pass --force")
    fleet = Fleet(args.fleet_id, args.name, args.faction, args.profile)
    (add_forward if args.type == "forward" else add_reserve)(fleet)
    fleet_text = fleet.render()
    ids = [u["id"] for u in fleet.units] + [args.fleet_id]
    if len(ids) != len(set(ids)):
        parser.error("internal error: generated duplicate unit IDs")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(fleet_text, encoding="utf-8")
    ship_count = sum(1 for u in fleet.units if u["echelon"] == "ship")
    print(f"Wrote {args.type.upper()} fleet: {len(fleet.units) + 1} units, {ship_count} ships -> {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
